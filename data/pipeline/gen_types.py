"""
Generate the Go and TypeScript types for the Airport document from the Contract.

Writes two committed files; do not edit them by hand:
    backend/search/airport_gen.go
    frontend/src/types/airport.gen.ts

Usage:
    python gen_types.py
"""

from __future__ import annotations

import re
from pathlib import Path

from airport_contract import ENUM, INTEGER, POINT, SERVED_FIELDS, STRING, Field

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
GO_OUT = REPO_ROOT / "backend" / "search" / "airport_gen.go"
TS_OUT = REPO_ROOT / "frontend" / "src" / "types" / "airport.gen.ts"

HEADER = "Code generated by data/pipeline/gen_types.py from airport_contract.py. DO NOT EDIT."


def go_name(json_name: str) -> str:
    """iata_code -> IataCode, CITY_NAME -> CityName, _geo -> Geo."""
    words = [w for w in re.split(r"_+", json_name) if w]
    return "".join(w[:1].upper() + w[1:].lower() for w in words)


def go_enum_type(field: Field) -> str:
    return "Airport" + go_name(field.name)


def go_type(field: Field) -> str:
    if field.kind == INTEGER:
        return "int"
    if field.kind == POINT:
        return "*GeoPoint"
    if field.kind == ENUM:
        return go_enum_type(field)
    return "string"


def render_go_enum(field: Field) -> str:
    typ = go_enum_type(field)
    width = max(len(typ + go_name(v)) for v in field.values)
    consts = "\n".join(
        f'\t{typ + go_name(v):<{width}} {typ} = "{v}"' for v in field.values
    )
    return f"type {typ} string\n\nconst (\n{consts}\n)\n"


def go_tag(field: Field) -> str:
    omit = ",omitempty" if field.optional else ""
    return f'`json:"{field.name}{omit}"`'


def render_go() -> str:
    name_w = max(len(go_name(f.name)) for f in SERVED_FIELDS)
    type_w = max(len(go_type(f)) for f in SERVED_FIELDS)
    fields = "\n".join(
        f"\t{go_name(f.name):<{name_w}} {go_type(f):<{type_w}} {go_tag(f)}"
        for f in SERVED_FIELDS
    )
    enums = "\n".join(render_go_enum(f) for f in SERVED_FIELDS if f.kind == ENUM)
    names = "\n".join(f'\t"{f.name}",' for f in SERVED_FIELDS)
    return f"""// {HEADER}

package search

{enums}
type Airport struct {{
{fields}
}}

type GeoPoint struct {{
	Lat float64 `json:"lat"`
	Lng float64 `json:"lng"`
}}

// AttributesToRetrieve lists the Served fields requested from Meilisearch.
var AttributesToRetrieve = []string{{
{names}
}}
"""


def ts_type(field: Field) -> str:
    if field.kind == INTEGER:
        return "number"
    if field.kind == POINT:
        return "{ lat: number; lng: number }"
    if field.kind == ENUM:
        return " | ".join(f'"{v}"' for v in field.values)
    assert field.kind == STRING
    return "string"


def render_ts() -> str:
    lines = "\n".join(
        f"  {f.name}{'?' if f.optional else ''}: {ts_type(f)};" for f in SERVED_FIELDS
    )
    return f"// {HEADER}\n\nexport interface Airport {{\n{lines}\n}}\n"


def main() -> None:
    GO_OUT.write_text(render_go(), encoding="utf-8")
    TS_OUT.write_text(render_ts(), encoding="utf-8")
    print(f"wrote {GO_OUT.relative_to(REPO_ROOT)}")
    print(f"wrote {TS_OUT.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
